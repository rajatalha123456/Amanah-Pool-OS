export function translateToArabic(text: string): string {
  if (!text || typeof text !== "string") return text
  const trimmed = text.trim()
  if (!trimmed) return text
  if (ARABIC_PHRASE_DICTIONARY[trimmed]) return text.replace(trimmed, ARABIC_PHRASE_DICTIONARY[trimmed])
  const lower = trimmed.toLowerCase()
  for (const [key, val] of Object.entries(ARABIC_PHRASE_DICTIONARY)) {
    if (key.toLowerCase() === lower) return text.replace(trimmed, val)
  }
  return text
}
