/**
 * Universal text translation function.
 * Matches exact phrase or applies intelligent token replacement.
 */
export function translateToUrdu(text: string): string {
  if (!text || typeof text !== "string") return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  // Direct exact match
  if (URDU_PHRASE_DICTIONARY[trimmed]) {
    return text.replace(trimmed, URDU_PHRASE_DICTIONARY[trimmed]);
  }

  // Check case-insensitive match
  const lowerTrimmed = trimmed.toLowerCase();
  for (const [key, val] of Object.entries(URDU_PHRASE_DICTIONARY)) {
    if (key.toLowerCase() === lowerTrimmed) {
      return text.replace(trimmed, val);
    }
  }

  return text;
}
